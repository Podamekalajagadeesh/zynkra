import { analyzeNeuralAuthenticity } from './deepfake-detection';

/**
 * Converted from `test/deepfake-detection.test.js`, which used `node:test`
 * inside a Jest project whose `testMatch` is `['**\/*.spec.ts', '**\/*.test.ts']`.
 * That file was never collected by any runner, so these assertions had never
 * been executed once — they looked like coverage while covering nothing.
 *
 * The original assertions were re-checked against the current implementation
 * before being carried over; all of them still hold. The cases below were then
 * traced by hand to pin the scoring bands, which nothing covered before.
 */
describe('analyzeNeuralAuthenticity', () => {
  it('detects authentic personal memory cues', () => {
    const result = analyzeNeuralAuthenticity({
      content:
        'I still remember the rain on the train window during our trip to Lisbon, the smell of coffee, and how my hands felt cold when I held your sleeve.',
      memoryMetadata: {
        emotions: { joy: 20, sadness: 10, excitement: 15, calm: 0, anger: 0, surprise: 10, love: 25, fear: 5 },
        context: { location: { name: 'Lisbon train station' } },
        sensory: {
          visual: [{ url: 'https://example.com/photo.jpg', type: 'image' }],
          audio: [{ url: 'https://example.com/audio.mp3', type: 'audio' }],
        },
      },
    });

    expect(result.verdict).toBe('likely_authentic');
    expect(result.score).toBeGreaterThanOrEqual(0.65);
    expect(result.signals).toContain('sensory media present');
  });

  it('flags generic AI-style phrases as synthetic', () => {
    const result = analyzeNeuralAuthenticity({
      content:
        'A stunningly perfect cinematic scene generated by a prompt that vividly captures beauty and harmony.',
      memoryMetadata: {},
    });

    expect(result.verdict).toBe('likely_synthetic');
    expect(result.score).toBeLessThan(0.5);
    expect(result.signals.some((signal) => signal.includes('synthetic'))).toBe(true);
  });

  it('lands in the needs_review band for a single authentic cue', () => {
    // 0.2 base + 0.35 personal detail + 0.05 for the one "remember" hit = 0.6,
    // which is above the synthetic cutoff and below the authentic one.
    const result = analyzeNeuralAuthenticity({ content: 'I remember' });

    expect(result.score).toBeCloseTo(0.6, 3);
    expect(result.verdict).toBe('needs_review');
  });

  it('treats an empty memory as synthetic rather than neutral', () => {
    // Worth pinning because it is surprising: with no content and no metadata
    // the score never moves off the 0.2 base, which falls in the synthetic band.
    const result = analyzeNeuralAuthenticity({});

    expect(result.score).toBe(0.2);
    expect(result.verdict).toBe('likely_synthetic');
    expect(result.signals).toEqual(['no strong authenticity markers detected']);
  });

  it('normalizes case and punctuation before matching cues', () => {
    const shouty = analyzeNeuralAuthenticity({ content: 'I REMEMBER!!! the RAIN...' });
    const plain = analyzeNeuralAuthenticity({ content: 'i remember the rain' });

    expect(shouty.score).toBe(plain.score);
  });

  it('clamps the score to 1 no matter how many signals stack up', () => {
    const result = analyzeNeuralAuthenticity({
      content:
        'I still remember the rain, the smell, my hands were cold, the sound, when I was young, last night.',
      memoryMetadata: {
        emotions: { joy: 5 },
        context: { location: { name: 'Porto' } },
        sensory: { visual: [{ url: 'a' }], audio: [{ url: 'b' }] },
      },
    });

    expect(result.score).toBe(1);
    expect(result.confidence).toBeLessThanOrEqual(0.99);
  });

  it('never returns a score outside 0..1', () => {
    const synthetic = analyzeNeuralAuthenticity({
      content: 'stunningly cinematic beautifully crafted highly polished ultra realistic',
    });

    expect(synthetic.score).toBeGreaterThanOrEqual(0);
    expect(synthetic.score).toBeLessThanOrEqual(1);
  });
});
